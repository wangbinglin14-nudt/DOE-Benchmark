"""Generate the case-library datasheet (Datasheets for Datasets template).

Emits ``docs/CASE_LIBRARY_DATASHEET.md`` from the frozen case registry, the
case-validation ledger and the archived sweep manifest, so that the Data
Availability statement's claim that a datasheet is distributed with the
archive is backed by a generated, auditable file.

Run:  python scripts/generate_case_library_datasheet.py
"""
from __future__ import annotations

import csv
import hashlib
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import doe_testbed as db  # noqa: E402

STATUS_CSV = ROOT / "docs" / "case_validation_status.csv"
OUTPUT = ROOT / "docs" / "CASE_LIBRARY_DATASHEET.md"
MANIFEST = ROOT / "benchmark" / "results" / "full_benchmark" / "RUN_MANIFEST.json"
FULL_CSV = ROOT / "benchmark" / "results" / "full_benchmark" / "results.csv"

TIER_BY_DISPOSITION = {
    "plausibility only": "targeted_plausibility_only",
    "analytic control": "targeted_analytical_control",
    "accepted after resweep": "external_note_targeted_regression",
}


def _rows() -> list[dict[str, str]]:
    with STATUS_CSV.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    metas = list(db.list_cases())
    status = {r["case_id"]: r for r in _rows()}

    domains = Counter(str(m.domain) for m in metas)
    dims = sorted(int(m.dim_input) for m in metas)
    tiers = Counter(
        status[m.case_id]["risk_level"] for m in metas if m.case_id in status
    )
    n_failure = sum(1 for m in metas if m.has_failure_boundary)

    lines: list[str] = []
    lines.append("# Case Library Datasheet — DOE-Benchmark")
    lines.append("")
    lines.append(
        "This datasheet follows the *Datasheets for Datasets* template "
        "(Gebru et al., *Commun. ACM* **64**, 86--92, 2021) and documents the "
        "case library distributed with the DOE-Benchmark research archive. "
        "It is auto-generated by `scripts/generate_case_library_datasheet.py` "
        "from the frozen case registry, `docs/case_validation_status.csv` and "
        "the archived sweep manifest; edit the sources, not this file."
    )
    lines.append("")

    lines.append("## Motivation")
    lines.append("")
    lines.append(
        "- **Purpose.** Provide deterministic, physics-grounded engineering "
        "simulators for evaluating design-of-experiments sampling and "
        "surrogate methods under response structures that closed-form "
        "analytical test functions do not represent."
    )
    lines.append(
        "- **Created by.** Binglin Wang (National University of Defense "
        "Technology, NUDT, China) and contributors; see `CITATION.cff`."
    )
    lines.append(
        "- **Funding.** The accompanying manuscript reports support from "
        "NSAF (No. U2230208), the National Natural Science Foundation of China "
        "(Grant Nos. 12371259 and 12671309), its Young Scientists Fund "
        "(Grant No. 12401327), and the Fundamental Research Funds for the "
        "Central Universities (No. 63263100), as supplied by the author."
    )
    lines.append("")

    lines.append("## Composition")
    lines.append("")
    lines.append(f"- **Cases.** {len(metas)} deterministic, single-fidelity simulators.")
    lines.append(
        f"- **Input dimension.** {dims[0]}--{dims[-1]} (median {dims[len(dims) // 2]})."
    )
    lines.append("- **Domains.** " + ", ".join(f"{k} ({v})" for k, v in sorted(domains.items())) + ".")
    lines.append(
        f"- **Outputs.** Every case returns three outputs; {n_failure} cases define an "
        "explicit failure boundary used by the D3 reliability analysis."
    )
    lines.append("- **Risk tiers (case-validation ledger).** "
                 + ", ".join(f"{k}: {v}" for k, v in sorted(tiers.items())) + ".")
    lines.append(
        "- **Labels.** Response-topology tags, Sobol' first-order/total-effect "
        "fingerprints, failure thresholds and evidence tiers are recorded in "
        "the per-case registry metadata and in "
        "`docs/CASE_VALIDATION_SUMMARY.md`."
    )
    lines.append("")
    lines.append("| Case | Domain | $d$ | Failure boundary | Risk tier | Targeted test |")
    lines.append("|---|---|---:|---|---|---|")
    for m in sorted(metas, key=lambda x: (str(x.domain), int(x.dim_input), x.case_id)):
        row = status.get(m.case_id, {})
        test = row.get("targeted_physics_test", "NONE")
        lines.append(
            f"| `{m.case_id}` | {m.domain} | {int(m.dim_input)} | "
            f"{'Yes' if m.has_failure_boundary else 'No'} | "
            f"{row.get('risk_level', 'n/a')} | "
            f"{'`' + test + '`' if test != 'NONE' else '—'} |"
        )
    lines.append("")

    lines.append("## Collection process")
    lines.append("")
    lines.append(
        "- **How generated.** Each case implements a documented low-order "
        "physical model (for example Euler--Bernoulli beam eigenvalue "
        "problems, lumped thermal networks, Breguet-range surrogates) behind a "
        "common normalised `BaseCase.evaluate` interface."
    )
    lines.append(
        "- **Sampling.** Inputs are sampled by the benchmark samplers; ground "
        "truth comes from the simulator itself, so no measurement noise enters "
        "the case library."
    )
    lines.append(
        "- **Validation.** Cases carry targeted physics regression tests that "
        "pin equations, trends and failure contracts. Evidence tiers separate "
        "cases with external validation notes from plausibility-only cases; "
        "see `docs/CASE_VALIDATION_SUMMARY.md` and "
        "`docs/case_validation_status.csv`."
    )
    lines.append("")

    lines.append("## Uses")
    lines.append("")
    lines.append(
        "- **Intended use.** Benchmarking sampling, surrogate-model and "
        "reliability-estimation methods; studying analytical-to-physical "
        "transfer of method rankings, sample budgets and risk calibration."
    )
    lines.append(
        "- **Out-of-scope use.** The cases are low-order simulators, not "
        "validated high-fidelity models. They must not be used as certified "
        "safety, certification or design-approval evidence, and quantitative "
        "estimates apply only to the tested case panel, domains and budgets."
    )
    lines.append(
        "- **Known limitations.** Deterministic and single-fidelity; "
        "plausibility-only cases lack external case-level validation; the "
        "case identifiers' `_Nd` suffixes sometimes denote physical spatial "
        "dimension rather than input dimension."
    )
    lines.append("")

    lines.append("## Distribution")
    lines.append("")
    lines.append(
        "- **Files.** Case sources under `doe_testbed/cases/`, the registry "
        "under `doe_testbed/registry/`, the validation ledger under `docs/`, "
        "and raw sweep outputs under `benchmark/results/`."
    )
    if MANIFEST.exists():
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
        window = manifest.get("run_window", {})
        lines.append(
            "- **Archived sweep window.** "
            f"{window.get('started_at_utc')} to {window.get('finished_at_utc')} "
            "(see `benchmark/results/full_benchmark/RUN_MANIFEST.json`)."
        )
    if FULL_CSV.exists():
        lines.append(
            "- **Headline raw-results fingerprint (SHA-256).** "
            f"`{_sha256(FULL_CSV)}`."
        )
    lines.append(
        "- **Licence.** MIT; see `LICENSE`."
    )
    lines.append("")

    lines.append("## Maintenance")
    lines.append("")
    lines.append(
        "- **Steward.** The corresponding author maintains the registry and "
        "this datasheet."
    )
    lines.append(
        "- **Extension policy.** New cases are added through the registry; "
        "metadata, bounds, topology tags and failure thresholds are frozen "
        "per benchmark version, and the case-validation ledger plus this "
        "datasheet are regenerated on every change."
    )
    lines.append(
        "- **Versioning.** The registry pins a per-benchmark version; the "
        "manuscript's analysis is bound to the archived sweep fingerprint "
        "recorded above."
    )
    lines.append(
        "- **Support.** Questions and corrections are handled through the "
        "public repository issue tracker once the archive is deposited."
    )
    lines.append("")

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="")
    print(f"[ok] wrote {OUTPUT.relative_to(ROOT)} ({len(metas)} cases)")


if __name__ == "__main__":
    main()
